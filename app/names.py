def fold_confusables(name: str) -> str:
    """Свести латинские буквы-двойники к кириллице — ТОЛЬКО там, где это OCR.

    Сводить всё подряд нельзя: настоящая латинская фамилия «Сергей Beck»
    превратится в кашу. Признаки именно ошибки распознавания — слово смешанного
    алфавита («Зoя» с латинской o) или одинокая латинская буква при
    кириллическом имени («Зоя P»), то есть инициал не в той раскладке.
    """
    words = (name or "").split()
    has_cyr = any(_CYR_RE.search(w) for w in words)
    out = []
    for w in words:
        mixed = _CYR_RE.search(w) and _LAT_RE.search(w)
        lone = has_cyr and len(w.strip(".")) == 1 and _LAT_RE.fullmatch(w.strip("."))
        out.append(w.translate(_CONFUSABLES) if (mixed or lone) else w)
    return " ".join(out)


def _shape(s: str) -> str:
    """Исправить форму подписи, НЕ трогая регистр.

    Регистр здесь трогать нельзя: по нему looks_like_name отличает имя от
    мусора («rear TL» от «константин П»). Если причесать регистр раньше
    проверки, мусор станет неотличим от имени.

    Порядок важен: значок интерфейса снимается ПОСЛЕ сведения двойников —
    иначе латинская «P» в «Зоя P» выглядит таким значком, и честный инициал
    отрезается, порождая новый дубль вместо склейки.
    """
    s = fold_confusables((s or "").strip())
    s = re.sub(r"^([А-ЯЁ][а-яё]{2,})([А-ЯЁ])$", r"\1 \2", s)   # ЗояР → Зоя Р
    m = re.match(r"^(.*[А-Яа-яЁё].*?)[\s.]+([A-Za-z])$", s)    # «… W» — значок
    return (m.group(1) if m else s).strip(" .")


def normalise(s: str) -> str:
    """Привести подпись к виду, в котором её писал человек (для показа)."""
    # OCR иногда теряет заглавную: «константин П» — это человек, а не мусор.
    return " ".join(w[:1].upper() + w[1:] if w else w for w in _shape(s).split())


def looks_like_name(s: str) -> bool:
    """Похоже ли на имя человека, а не на подпись элемента интерфейса."""
    s = _shape(s)          # форму чиним, регистр оставляем — он тут признак
    if not (2 <= len(s) <= 40) or any(ch.isdigit() for ch in s):
        return False
    if re.search(r"[^\w\s.\-ёЁ]", s):        # пунктуация → чат/интерфейс
        return False
    words = s.split()
    if not 1 <= len(words) <= 3:
        return False
    low = s.lower()
    plain = [w.strip(".").lower() for w in words]
    if low in NAME_STOP or any(w in NAME_STOP for w in plain):
        return False
    # Одно служебное слово — и это уже не имя, а обрывок фразы с экрана.
    if any(w in _NON_NAME_WORDS for w in plain):
        return False
    if len(words) == 1 and low.endswith(_NOT_NAME_SUFFIX):
        return False
    # Одиночное слово ЦЕЛИКОМ капслоком — это надпись с экрана, а не подпись
    # человека: «CBASU», «RIDES», «ЗАДАНИЕ», «РЕАСН», «BOHOK» — все из реальных
    # протоколов. Требуем именно одно слово без единой строчной буквы, поэтому
    # «HR Светлана» и «Сергей Beck» проходят как прежде.
    if len(words) == 1 and len(s) >= 4 and s == s.upper() and s != s.lower():
        return False
    if all(w[0].isupper() for w in words):
        return True
    # OCR иногда теряет заглавную у имени: «константин П». Считаем именем, если
    # строчное слово — КИРИЛЛИЦА длиной от трёх букв и рядом есть слово с
    # заглавной (инициал или фамилия). Латинский мусор («rear TL») так не
    # пройдёт: терять реального участника хуже, чем пропустить лишнюю строку,
    # но и открывать ворота всему подряд нельзя.
    if len(words) < 2 or not any(w[0].isupper() for w in words):
        return False
    return all(w[0].isupper() or (len(w) >= 3 and _CYR_WORD_RE.fullmatch(w))
               for w in words)


def key(s: str) -> str:
    """Ключ для дедупликации: нормализованный вид без регистра."""
    return " ".join(normalise(s).lower().split())


# Кириллица → латиница для сравнения имён. Телемост показывает подпись так, как

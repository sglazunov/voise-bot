# Служебные слова русского языка: в имени человека их не бывает НИКОГДА.
# Ловят обрывки текста с демонстрируемого экрана — слайдов и документов. OCR
# отдаёт их как «Слово Слово Слово» с заглавных, и по форме они неотличимы от
# «Иван Петрович Сидоров». В боевом протоколе так пришли «Определяется Как

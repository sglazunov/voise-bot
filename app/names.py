def addressee(text: str, known: list[str] | None = None) -> str:
    """К кому обращаются в реплике: «Паша, можешь собрать…», «ты, Паша, поставь».

    Ревью 128 протоколов: цитата «Паша, можешь собрать список шаблонов» давала
    ответственного «—», а «я хочу, чтобы ты, Паша, поставил задачи» —
    говорящего. Обращение по имени внутри реплики модель не читала.

    Слово перед запятой сверяется с известными участниками (по имени или его
    уменьшительной форме); незнакомое слово («Нет,», «Хорошо,») — не имя.
    Если человек в той же реплике берёт задачу сам («я сделаю»), обращение
    исполнителя не меняет — возвращается пустая строка.
    """
    body = _LABEL_RE.sub(" ", text or "")
    if _FIRST_PERSON_RE.search(body):
        return ""
    firsts: list[tuple[str, str]] = []
    for k in known or []:
        kk = key(k)
        if kk:
            firsts.append((kk.split()[0], normalise(k)))
    for m in _VOCATIVE_RE.finditer(body):
        w = m.group(1).lower()
        full = (_DIMINUTIVES.get(w) or _VOCATIVE_SHORT.get(w) or w).replace("ё", "е")
        w = w.replace("ё", "е")
        if len(w) < 3 and w not in _VOCATIVE_SHORT:
            continue
        for first, full_name in firsts:
            f = first.replace("ё", "е")
            if f in (w, full) or (len(full) >= 4 and f.startswith(full)) \
                    or (len(f) >= 4 and full.startswith(f)):
                return full_name
        if w in _DIMINUTIVES or w in _VOCATIVE_SHORT:
            # Известного участника с таким именем нет — отдаём полное имя:
            # лучше «Павел», чем «—», проверка цитатой всё равно рядом.
            return full.capitalize()
    return ""


def canonical(caption: str, known: list[str] | None = None) -> str:
    """Подпись плитки → известное имя, если подпись — его искажение.

    Боевые случаи: «ЗЖКИРИЛЛ БУБНОВ» (OCR приклеил мусор спереди), «Mapua H»
    (вся подпись прочитана латиницей — fold_confusables такое не трогает,
    потому что настоящая латинская фамилия выглядит так же), «Зоя P».
    Известные имена берутся из постоянного контекста и карточки серии — их
    написал человек, им и верим. Без совпадений — только форма (регистр).
    """
    c = _uncaps(normalise(caption))
    ck = key(c)
    if not ck:
        return c
    ct = translit_key(c)
    # Подпись, прочитанная латиницей целиком: сводим по расширенной таблице
    # OCR-двойников (u≈и, m≈м, h≈н…) — только для сравнения, не для показа.
    cf = " ".join(c.translate(_OCR_LATIN).lower().split())
    for k in known or []:
        kk = key(k)
        if not kk:
            continue
        if ck == kk or ck.replace(" ", "") == kk.replace(" ", ""):
            # «Зояр» — OCR склеил «Зоя Р»: сравниваем и без пробелов.
            return normalise(k)
        # Мусор спереди/сзади: «зжкирилл бубнов» кончается на «кирилл бубнов».
        if len(kk) >= 6 and (ck.endswith(" " + kk) or ck.endswith(kk)) \
                and len(ck) - len(kk) <= 3:
            return normalise(k)
        # Та же подпись в другом алфавите / с парой опечаток OCR: сравниваем
        # и в транслите, и после сведения латиницы к кириллице целиком
        # («Mapua H» → «Марuа Н» ≈ «Мария Н»).
        kt = translit_key(k)
        if abs(len(kt) - len(ct)) <= 3 and len(kt) >= 5 \
                and (difflib.SequenceMatcher(None, ct, kt).ratio() >= 0.8
                     or difflib.SequenceMatcher(None, cf, kk).ratio() >= 0.8):
            return normalise(k)
    return c

def preset_rules(name: str | None, custom: dict | None = None) -> str:
    """The extra prompt rules of a preset; '' for universal/unknown.
    `custom` is the team's own presets {name: rules} — they win over builtins."""
    name = (name or "").strip()
    if custom and name in custom:
        return str(custom[name] or "")
    return str((PROTOCOL_PRESETS.get(name) or {}).get("rules") or "")


# Приоритет автоопределения: «Демо для заказчика» — демо, «Ревью макетов с
# заказчиком» — ревью; «заказчик» и «лидеры» решают, когда специфичнее нет.
_DETECT_ORDER = ("demo", "review", "one_on_one", "planerka", "client",
                 "leaders", "design")


def preset_for_title(title: str | None) -> str:
    """Auto-pick a preset from the meeting title (scheduler's «авто» mode).

    Ключевое слово должно совпадать с НАЧАЛОМ слова названия (или быть
    фразой из нескольких слов, стоящей по границе слов): подстрочный поиск
    делал из «ОД сайт, РЕдизайн, магазин» встречу типа «дизайн», а из
    «статусы заказов» — планёрку.
    """
    low = (title or "").lower().replace("ё", "е")
    words = re.findall(r"[\w-]+", low, re.UNICODE)
    for name in _DETECT_ORDER:
        p = PROTOCOL_PRESETS.get(name) or {}
        for k in p.get("keywords") or ():
            k = k.lower().replace("ё", "е")
            if " " in k or ":" in k:
                if re.search(r"(?<![\w])" + re.escape(k), low):
                    return name
            elif any(w.startswith(k) for w in words):
                return name
    return "universal"



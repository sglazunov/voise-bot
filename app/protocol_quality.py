"""Метрики «читаемости» протокола: ловим пустые разделы до того, как их увидит человек.

Жалоба с боевых протоколов была не «мало текста», а «теряется смысл»: раздел
пересказывает собственный заголовок и не добавляет ни одного факта. Живой пример
из операционной встречи на 1 ч 18 мин:

    Бэклог и задачи
    «Обсуждаются задачи и бэклог. Решается вопрос о добавлении задач в бэклог.»

Формально протокол есть, тем девятнадцать — а узнать из него нечего. Второй тот же
по природе дефект: «О чём шёл разговор» вместо сути пересказывает оглавление
(«обсуждались темы, включая приветствие, повестку дня, бэклог…»).

Здесь только детекторы — чистые функции без обращения к ИИ. Их использует и
runtime (чтобы перегенерировать пустую тему), и оценка качества на эталонах.
"""
from __future__ import annotations

import re

# Слова-пустышки: сами по себе ничего не сообщают о встрече. Если раздел
# состоит почти только из них и слов заголовка — содержания в нём нет.
_FILLER = {
    "обсуждается", "обсуждаются", "обсуждали", "обсудили", "обсуждение",
    "рассматривается", "рассматриваются", "рассмотрели",
    "решается", "решаются", "решался", "решение", "вопрос", "вопросы",
    "затрагивается", "затрагиваются", "поднимается", "поднимался",
    "говорится", "говорили", "речь", "тема", "темы", "участники", "участник",
    "встреча", "встречи", "необходимость", "необходимости", "различных",
    "связанные", "связанных", "также", "далее", "затем", "кроме",
    "который", "которые", "которых", "этом", "этой", "этого", "также",
}
_STOP = {
    "и", "в", "во", "на", "с", "со", "о", "об", "по", "к", "у", "за", "из",
    "для", "не", "что", "как", "а", "но", "или", "то", "же", "бы", "ли",
    "был", "была", "было", "были", "быть", "есть", "это", "их", "его", "её",
    "они", "он", "она", "мы", "вы", "я", "при", "от", "до", "над", "под",
}
_STEM_LEN = 5  # грубая нормализация: «фильтры» ≈ «фильтров»
# Пустышки сравниваем ПО ОСНОВЕ, иначе русские окончания обходят список:
# «вопрос» в наборе есть, а «вопросов» — уже нет, и раздел из одних служебных
# оборотов проходит как содержательный.
_FILLER_STEMS = {w[:_STEM_LEN] for w in _FILLER}
# Доля пустышек, выше которой фраза считается голым каркасом («обсуждается…
# решается вопрос о…») даже когда в ней названы предмет или система.
_SCAFFOLD_RATIO = 0.5


def _words(text: str) -> list[str]:
    return re.findall(r"[\w-]+", (text or "").lower(), re.UNICODE)


def _is_filler(word: str) -> bool:
    return word[:_STEM_LEN] in _FILLER_STEMS


def _stems(text: str) -> set[str]:
    """Значимые основы: без стоп-слов, без пустышек, без коротких хвостов."""
    out = set()
    for w in _words(text):
        if w in _STOP or _is_filler(w) or len(w) < 3:
            continue
        out.add(w[:_STEM_LEN])
    return out


def has_specifics(text: str) -> bool:
    """Есть ли в тексте конкретика — числа, даты, проценты, имена собственные,
    латиница (названия систем). Именно это отличает содержательный раздел от
    пересказа заголовка."""
    t = text or ""
    if re.search(r"\d", t):                       # числа, сроки, проценты
        return True
    if re.search(r"[A-Za-z]{2,}", t):             # CRM, Weeek, Figma
        return True
    # Имя собственное в середине предложения (не первое слово).
    for sent in re.split(r"(?<=[.!?])\s+", t):
        toks = sent.split()
        if any(w[:1].isupper() for w in toks[1:] if len(w) > 2):
            return True
    return False


def filler_ratio(text: str) -> float:
    """Доля слов-пустышек среди значимых. «Обсуждается вопрос о необходимости…»
    даёт высокую долю: предложение построено целиком из служебных оборотов."""
    sig = [w for w in _words(text) if w not in _STOP and len(w) >= 3]
    if not sig:
        return 1.0
    return sum(1 for w in sig if _is_filler(w)) / len(sig)


def topic_is_empty(topic: str, details: str, min_words: int = 25,
                   filler_limit: float = 0.4) -> bool:
    """Раздел «ни о чём»: пересказ заголовка без единого факта.

    Порядок проверок:
      * объёмный текст с конкретикой — содержательный, вопросов нет;
      * своих слов сверх заголовка нет вовсе — пусто;
      * есть конкретика (числа, сроки, имена, названия систем) — считаем
        содержательным даже если коротко: «Решили перенести релиз на 25 июля»
        это факт, а не вода;
      * иначе пусто, если своих слов почти нет ИЛИ текст собран из служебных
        оборотов («обсуждается… решается вопрос о необходимости…»).
    """
    d = (details or "").strip()
    if not d:
        return True
    words = _words(d)
    own = _stems(d) - _stems(topic)         # что раздел добавил сверх заголовка
    specific = has_specifics(d)
    fr = filler_ratio(d)
    if len(words) >= min_words and specific:
        return False
    if not own:
        return True
    # Упоминание названия само по себе не делает раздел содержательным:
    # «Обсуждается вопрос о МСУ и аватаре. Решается вопрос о добавлении
    # аватара» называет предмет, но не сообщает НИЧЕГО о нём. Если фраза
    # больше чем наполовину состоит из служебных оборотов — она пустая.
    if specific:
        return fr >= _SCAFFOLD_RATIO
    return len(own) <= 3 or fr >= filler_limit


def summary_is_toc(summary: str, topics: list[str], ratio: float = 0.6) -> bool:
    """«О чём шёл разговор» пересказывает оглавление вместо сути.

    Осторожно: само по себе совпадение с названиями тем — НЕ признак. Хороший
    краткий пересказ естественно упоминает те же темы, о которых шла речь.
    Оглавление отличает другое: перечислив темы, оно не сообщает о них НИЧЕГО —
    ни цифр, ни решений, одни служебные обороты («обсуждались различные темы,
    включая…»). Поэтому требуем оба признака сразу.
    """
    titles = [t for t in (topics or []) if (t or "").strip()]
    s = (summary or "").strip()
    if len(titles) < 3 or not s:
        return False
    s_stems = _stems(s)
    hit = sum(1 for t in titles if _stems(t) and _stems(t) <= s_stems)
    if hit / len(titles) < ratio:
        return False
    return not has_specifics(s) or filler_ratio(s) >= _SCAFFOLD_RATIO


def report(protocol: dict) -> dict:
    """Сводка дефектов по готовому протоколу — для метрик и для UI.

    `actionable` (задачи + решения) считается отдельно: по боевым данным ноль
    задач встречался ТОЛЬКО на длинных встречах — там, где ответ движка
    обрезался по лимиту. Пустой список по рабочей встрече почти всегда значит,
    что задачи не выписали, а не что их не было, — такое должно быть заметно.
    """
    detailed = protocol.get("detailed") or []
    empty = [i for i, b in enumerate(detailed)
             if topic_is_empty((b or {}).get("topic", ""), (b or {}).get("details", ""))]
    titles = [(b or {}).get("topic", "") for b in detailed]
    tasks = sum(len(protocol.get(k) or [])
                for k in ("tasks", "minor_tasks", "done_tasks"))
    decisions = len(protocol.get("decisions") or [])
    return {
        "topics": len(detailed),
        "empty_topics": empty,
        "empty_ratio": round(len(empty) / len(detailed), 3) if detailed else 0.0,
        "summary_is_toc": summary_is_toc(protocol.get("summary", ""), titles),
        "tasks_total": tasks,
        "decisions_total": decisions,
        # Разбор есть, а выжимки нет — читать такой протокол незачем.
        "no_actionable": bool(detailed) and tasks == 0 and decisions == 0,
    }

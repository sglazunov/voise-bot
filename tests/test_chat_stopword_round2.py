    def test_сдвиг_окна_счётчик_вырос(self):
        b = _bot()
        assert _feed(b, ["Сергей Беск", "стоп", "11:39"]) is False
        assert _feed(b, ["Сергей Беск", "стоп", "11:12",
                         "Сергей Беск", "стоп", "11:39"]) is False

    def test_дописанное_ниже_ловится_даже_дословно_равное(self):
        b = _bot()
        assert _feed(b, ["Сергей Беск", "стоп", "11:39"]) is False
        assert _feed(b, ["Сергей Беск", "стоп", "11:39", "Сергей Беск", "стоп", "11:39"]) is True

    def test_одно_ушло_сверху_одно_пришло_снизу(self):
        b = _bot()

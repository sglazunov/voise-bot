# --- Выжившие мутанты второго раунда ----------------------------------------
class TestМутантыРаунда2:

    def test_якоря_запоминаются_на_пути_pinned(self):
        """Раздел дня достроен по доказанному низу — сообщения этого окна
        тоже якоря: окно потом сдвинется, а низ доказать не удастся."""
        b = _bot()
        pins = iter([False, True, False])
        b._pin_chat_bottom = lambda w: next(pins)
        assert _feed(b, ["Сегодня", "Иван", "привет", "11:05"]) is False
        assert _feed(b, ["Иван", "привет", "11:05", "Анна", "ок", "11:10",
                         "Олег", "да", "11:12"]) is False
        assert _feed(b, ["Анна", "ок", "11:10", "Сергей Беск", "стоп", "11:26"]) is True

    def test_якоря_запоминаются_после_среза(self):
        b = _bot()
        assert _feed(b, ["Сегодня", "Иван", "привет", "11:05"]) is False
        assert _feed(b, ["Иван", "привет", "11:05", "Анна", "ок", "11:10",
                         "Олег", "да", "11:12"]) is False
        assert _feed(b, ["Анна", "ок", "11:10", "Сергей Беск", "стоп", "11:26"]) is True

    def test_тройка_с_пустой_строкой_не_якорь(self):
        b = _bot()
        assert _feed(b, ["Сегодня", "Иван Р.", "привет", "11:05", "",
                         "Анна", "ок", "11:10"]) is False
        assert _feed(b, ["привет", "11:05", "", "Сергей Беск", "стоп", "11:26"]) is False

    def test_day_headers_с_раскладкой_в_frame_chat_stop(self):
        """Область «all», раскладка «время перед текстом»: сообщение
        «Понедельник» со своим временем НАД ним — не дата, и дописанная
        команда ловится."""
        b = _bot()
        base = ["Иван", "11:20", "Понедельник", "Анна", "11:25", "ок"]
        assert b._frame_chat_stop("f", "all", base, "стоп", False, 660, 690) is False
        assert b._frame_chat_stop("f", "all", base + ["Сергей Беск", "11:26", "стоп"],
                                  "стоп", False, 660, 690) is True

    def test_day_headers_с_раскладкой_в_frame_scope(self):
        b = _bot()
        b._today_seen_frames = {"f"}
        lines = ["Иван", "11:20", "Понедельник", "Анна", "11:25", "ок"]
        wall = dt.datetime(2026, 10, 30, 11, 30).timestamp()
        scope, out = b._frame_scope("f", lines, wall, True, False, "стоп")
        assert scope == "today" and out == lines



"""Стоп-слово, второй раунд адверсариального ревью 30.10
(`docs/АДВЕРСАРИАЛЬНОЕ-РЕВЮ-2026-10-30-2.md`, §5).

Принцип: ложная остановка режет живую встречу (хуже всего), пропущенная
команда лечится кнопкой «Стоп», `/stop` в Telegram и выходом по тишине. Где
правило неоднозначно — НЕ останавливаем.

Время в тестах: «сегодня» = 30.10.2026, бот вошёл в 11:00, сейчас 11:30.
"""
from __future__ import annotations

import datetime as dt

from app.automation.recorder.browser import TelemostBot


def _bot(joined="11:00", now="11:30", day=(2026, 10, 30)):
    b = TelemostBot.__new__(TelemostBot)
    b._chat_last_peek = 0.0
    b._chat_last_n = -1
    b._chat_scopes = {}
    b._chat_reads = 0
    h, m = map(int, now.split(":"))
    b._clock = lambda: dt.datetime(*day, h, m).timestamp()
    jh, jm = map(int, joined.split(":"))
    b._chat_since_min = jh * 60 + jm
    b.log = []
    b._on_log = b.log.append
    return b


def _feed(b, lines):
    b._read_all_text = lambda: "\n".join(lines)
    b._chat_last_peek = 0.0
    return b.maybe_chat_stop("стоп")


SEP = TelemostBot._FRAME_SEP
# Два старших раздела: над разделителем — время прошлого сообщения, и они
# голосуют за раскладку «время после текста» (как в живых логах).
OLD = ["9 октября", "Анна", "да", "11:00", "12 октября", "Олег", "ок", "11:01"]


# --- К: сообщение «Сегодня»/«30 октября» без голого времени прямо под ним ----
class TestСообщениеСегодняБезВремениПодНим:
    """Многострочное «Сегодня⏎в 11 созвон», «(изменено)», строка реакций:
    время не стоит СРАЗУ под строкой-датой, и она принималась за
    разделитель — старый «стоп 11:26» под ней срабатывал на первом чтении."""

    def test_многострочное_сообщение(self):
        b = _bot()
        assert _feed(b, ["9 октября", "Анна", "да", "11:00",
                         "16 октября", "Иван Р.", "Сегодня", "в 11 созвон", "11:20",
                         "Сергей Беск", "стоп", "11:26"]) is False

    def test_пометка_изменено(self):
        b = _bot()
        assert _feed(b, OLD + ["16 октября", "Иван Р.", "Сегодня", "(изменено)", "11:20",
                         "Сергей Беск", "стоп", "11:26"]) is False

    def test_строка_реакций_под_датой(self):
        b = _bot()
        assert _feed(b, OLD + ["16 октября", "Иван Р.", "30 октября", "👍 2", "11:20",
                         "Сергей Беск", "стоп", "11:26"]) is False

    def test_сообщение_с_заглавной_второй_строкой_под_автором(self):
        """«Сегодня⏎Созвон в 11» — вторая строка с заглавной (не отличить от
        автора), но строка-дата стоит ПОД автором, внутри сообщения: перед
        настоящим разделителем — время прошлого сообщения."""
        b = _bot()
        assert _feed(b, OLD + ["16 октября", "Иван Р.", "Сегодня", "Созвон в 11", "11:20",
                         "Сергей Беск", "стоп", "11:26"]) is False

    def test_сообщение_без_строки_автора_сразу_после_времени(self):
        """Подряд два сообщения одного автора: имя не повторяется, и строка
        «Сегодня» стоит сразу под временем прошлого сообщения."""
        b = _bot()
        assert _feed(b, ["16 октября", "Иван Р.", "привет", "11:19",
                         "Сегодня", "в 11 созвон", "11:20",
                         "Сергей Беск", "стоп", "11:26"]) is False

    def test_окно_начинается_с_такого_сообщения(self):
        b = _bot()
        assert _feed(b, ["Иван Р.", "Сегодня", "в 11 созвон", "11:20",
                         "Сергей Беск", "стоп", "11:26"]) is False

    def test_настоящий_разделитель_по_прежнему_работает(self):
        b = _bot()
        assert _feed(b, ["16 октября", "Иван Р.", "привет", "11:19",
                         "Сегодня", "Сергей Беск", "стоп", "11:26"]) is True

    def test_разделитель_вверху_окна_под_интерфейсом(self):
        """Новая комната: над «Сегодня» только подписи панели — структуры
        сообщений выше нет, разделитель принимается."""
        b = _bot()
        assert _feed(b, ["Чат", "Сегодня", "Сергей Беск", "стоп", "11:26"]) is True



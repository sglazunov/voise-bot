"""Темы-двойники схлопываются в одну.

Боевой случай (ЭМО 29.07): 25 тем на 4800 слов расшифровки, описания по 2-3
фразы. Среди заголовков — «Обсуждение планов на будущее» и «Обсуждение планов
на будущее и коммуникации», «Прототип» и «Тестирование прототипа», «Дизайн» и
«Обсуждение дизайна интерфейса». Одна тема размазана по нескольким разделам:
читать такой протокол не легче, чем протокол из воды.

Полагаться на промпт нельзя — проверено на summary, где Groq правило
игнорировал. Поэтому склейка механическая, и тесты фиксируют её границы: что
сливается, а что трогать НЕЛЬЗЯ.
"""
from app.analyze import merge_similar_topics


def _t(*titles):
    return [{"topic": t, "details": f"детали про {t.lower()}"} for t in titles]


class TestСклейка:
    def test_уточнённый_заголовок_это_та_же_тема(self):
        out = merge_similar_topics(_t("Обсуждение планов на будущее",
                                      "Обсуждение планов на будущее и коммуникации"))
        assert len(out) == 1
        # Остаётся более информативный заголовок.
        assert out[0]["topic"] == "Обсуждение планов на будущее и коммуникации"

    def test_вложенный_заголовок_сливается(self):
        assert len(merge_similar_topics(_t("Прототип", "Тестирование прототипа"))) == 1
        assert len(merge_similar_topics(_t("Дизайн", "Обсуждение дизайна интерфейса"))) == 1

    def test_тексты_объединяются_а_не_теряются(self):
        out = merge_similar_topics([
            {"topic": "Планы на будущее", "details": "решили перенести релиз"},
            {"topic": "Планы на будущее и сроки", "details": "срок — 25 июля"},
        ])
        assert len(out) == 1
        assert "перенести релиз" in out[0]["details"]
        assert "25 июля" in out[0]["details"]

    def test_вводное_слово_не_делает_темы_похожими(self):
        """«Обсуждение» есть почти у каждой темы — сравнивать надо по существу."""
        out = merge_similar_topics(_t("Обсуждение цвета подсветки",
                                      "Обсуждение названий элементов"))
        assert len(out) == 2


class TestНеСклеивать:
    def test_разные_темы_остаются_разными(self):
        titles = ["Цвет подсветки", "Названия элементов", "Календарь на экране",
                  "Конструктор тренажёра", "Проблема с фамилиями"]
        assert len(merge_similar_topics(_t(*titles))) == len(titles)

    def test_похожая_техника_но_разный_предмет(self):
        """iPad mini упоминается в обеих, но дизайн и разрешение — разное."""
        out = merge_similar_topics(_t("Дизайн для iPad mini",
                                      "Разрешение экрана iPad mini"))
        assert len(out) == 2

    def test_пустой_список_не_ломает(self):
        assert merge_similar_topics([]) == []

    def test_порядок_первого_вхождения_сохраняется(self):
        out = merge_similar_topics(_t("Прототип", "Цвет подсветки",
                                      "Тестирование прототипа"))
        assert [b["topic"] for b in out] == ["Тестирование прототипа", "Цвет подсветки"]

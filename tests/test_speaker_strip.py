"""Имена участников берутся из верхней полосы, а не с чужого экрана.

Боевой случай (CRM 28.07): во время демонстрации экрана в список участников
попали «Удалить», «Мероприятия», «Группы», «Роли Людей» — пункты меню из
демонстрируемой CRM. Причина: подсветка активного говорящего ищется по зелёной
рамке, а на чужом экране такие рамки тоже есть (кнопки, выделения).

Телемост при демонстрации уводит плитки участников в узкую полосу СВЕРХУ —
значит кандидат оттуда достовернее. Но когда никто не делится экраном, плитки
занимают всю сетку, и ограничиться полосой нельзя: тесты фиксируют оба режима.
"""
import numpy as np
import pytest

from app import speaker_id as S

pytest.importorskip("numpy")

H, W = 1080, 1920


def _frame(rects):
    """Кадр с зелёными РАМКАМИ указанных прямоугольников (r0, r1, c0, c1)."""
    a = np.zeros((H, W, 3), dtype=np.uint8)
    for (r0, r1, c0, c1) in rects:
        for t in range(4):
            a[r0 + t, c0:c1] = (60, 220, 90)
            a[r1 - t, c0:c1] = (60, 220, 90)
            a[r0:r1, c0 + t] = (60, 220, 90)
            a[r0:r1, c1 - t] = (60, 220, 90)
    return a


def test_при_демонстрации_берётся_плитка_из_верхней_полосы():
    """Зелёная кнопка на чужом экране не должна перебивать плитку участника."""
    frame = _frame([(30, 170, 1000, 1280),     # плитка участника в полосе
                    (700, 900, 300, 900)])      # крупная зелёная рамка в CRM
    box = S._active_bbox(frame)
    assert box is not None
    assert box[0] < H * S._TOP_STRIP, f"взята рамка вне верхней полосы: {box}"


def test_в_режиме_сетки_плитка_может_быть_где_угодно():
    """Без демонстрации участники занимают весь экран — полосой не ограничиваемся."""
    frame = _frame([(400, 900, 600, 1400)])
    box = S._active_bbox(frame)
    assert box is not None and box[0] > H * S._TOP_STRIP


def test_мелкая_рамка_вне_полосы_игнорируется():
    """Строка меню тонкая; плитка человека занимает заметную площадь."""
    assert S._active_bbox(_frame([(900, 940, 200, 500)])) is None


def test_без_зелёного_ничего_не_находим():
    assert S._active_bbox(np.zeros((H, W, 3), dtype=np.uint8)) is None

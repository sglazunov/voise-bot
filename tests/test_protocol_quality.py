"""Детектор пустых разделов протокола.

Жалоба людей была не «мало текста», а «теряется смысл»: раздел пересказывает
собственный заголовок и не сообщает ни одного факта. Все примеры ниже —
ДОСЛОВНО из боевых протоколов (операционная встреча на 1 ч 18 мин, где такими
оказались 11 тем из 19).

Тесты держат две границы сразу: пустышки должны ловиться, а живые разделы —
никогда не попадать под подозрение (ложное срабатывание хуже пропуска, потому
что уводит внимание от настоящих проблем).
"""
from app.protocol_quality import (filler_ratio, report, summary_is_toc,
                                  topic_is_empty)

# Дословно из протокола 23.07 — то, на что жаловались.
EMPTY_REAL = [
    ("Бэклог и задачи",
     "Обсуждаются задачи и бэклог. Решается вопрос о добавлении задач в бэклог."),
    ("Поиск дизайнеров",
     "Обсуждается вопрос о поиске дизайнеров. Решается вопрос о вакансии на дизайнера."),
    ("Технические вопросы",
     "Обсуждаются технические вопросы, связанные с протоколами и доступом к встречам. "
     "Решается вопрос о необходимости написания в поддержку."),
    ("План встречи и сервер",
     "Обсуждается план встречи и вопросы, связанные с сервером."),
    ("Приветствие и начало встречи",
     "Встреча начинается с приветствия всех участников. Обсуждается начало встречи "
     "и порядок обсуждения вопросов."),
    ("МСУ и аватар",
     "Обсуждается вопрос о МСУ и аватаре. Решается вопрос о добавлении аватара."),
]

# Так выглядит раздел, из которого что-то можно узнать.
SUBSTANTIAL = [
    ("Прототип клиентской части",
     "Договорились, что прототип клиентской части делает Кирилл до 25 июля. "
     "В Figma уже есть каркас карточки, но нет состояний ошибок."),
    ("Сервер почты",
     "Сейчас почта висит на стороннем сервисе, лимит 300 писем в сутки, этого "
     "не хватает при рассылке клиентам."),
    ("Короткий, но факт", "Решили перенести релиз на 25 июля."),
    ("Доступность интерфейса",
     "Решили добавить альтернативный текст ко всем изображениям тренажёра и "
     "проверить клавиатурную навигацию; проверку берёт на себя Кирилл."),
]


def test_боевые_пустышки_ловятся():
    missed = [t for t, d in EMPTY_REAL if not topic_is_empty(t, d)]
    assert not missed, f"не пойманы пустые разделы: {missed}"


def test_содержательные_разделы_не_трогаем():
    false_pos = [t for t, d in SUBSTANTIAL if topic_is_empty(t, d)]
    assert not false_pos, f"ложные срабатывания: {false_pos}"


def test_упоминание_названия_не_спасает_пустую_фразу():
    """«МСУ» и «аватар» названы, но о них ничего не сказано — это всё ещё пусто."""
    assert topic_is_empty("МСУ и аватар",
                          "Обсуждается вопрос о МСУ и аватаре. "
                          "Решается вопрос о добавлении аватара.")


def test_окончания_не_обходят_список_пустышек():
    """«вопросов»/«обсуждения» должны считаться пустышками так же, как «вопрос»."""
    assert filler_ratio("обсуждения вопросов участников") > 0.6


def test_пустой_details_это_пусто():
    assert topic_is_empty("Любая тема", "")


def test_summary_оглавление_ловится():
    topics = ["Приветствие и начало встречи", "Обсуждение повестки дня",
              "Бэклог и задачи", "Поиск дизайнеров"]
    toc = ("Встреча была посвящена обсуждению различных тем, включая приветствие "
           "и начало встречи, обсуждение повестки дня, бэклог и задачи, поиск "
           "дизайнеров.")
    assert summary_is_toc(toc, topics)


def test_нормальный_summary_не_ловится():
    topics = ["Доступность тренажёров", "Альтернативный текст", "Клавиатура"]
    good = ("Разбирали, почему тренажёры не проходят проверку доступности: у "
            "картинок нет альтернативного текста, часть кнопок недоступна с "
            "клавиатуры. Решили сначала закрыть alt-тексты к 1 августа, "
            "клавиатурную навигацию вынесли в отдельную задачу.")
    assert not summary_is_toc(good, topics)


def test_отчёт_считает_доли():
    proto = {"summary": "Решили перенести релиз на 25 июля.",
             "detailed": [{"topic": t, "details": d} for t, d in EMPTY_REAL[:2]]
                         + [{"topic": t, "details": d} for t, d in SUBSTANTIAL[:2]]}
    r = report(proto)
    assert r["topics"] == 4
    assert r["empty_topics"] == [0, 1]
    assert r["empty_ratio"] == 0.5
    assert r["summary_is_toc"] is False
